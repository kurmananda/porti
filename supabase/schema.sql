create table if not exists public.series (
  id text primary key,
  slug text not null unique,
  title text not null,
  years text not null default '',
  description text not null default '',
  created_at timestamptz not null default now(),
  sort_order integer not null default 0
);

create table if not exists public.works (
  id text primary key,
  series_id text not null references public.series(id) on delete cascade,
  title text not null,
  description text not null default '',
  image text not null,
  created_at timestamptz not null default now(),
  sort_order integer not null default 0
);

create table if not exists public.site_settings (
  id integer primary key check (id = 1),
  settings jsonb not null
);

create table if not exists public.exhibitions (
  id bigint generated by default as identity primary key,
  year text not null default '',
  title text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  topic text not null,
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.series enable row level security;
alter table public.works enable row level security;
alter table public.site_settings enable row level security;
alter table public.exhibitions enable row level security;
alter table public.contact_messages enable row level security;

revoke all on table public.series, public.works, public.site_settings,
  public.exhibitions, public.contact_messages from public, anon, authenticated;
grant all on table public.series, public.works, public.site_settings,
  public.exhibitions, public.contact_messages to service_role;
grant usage, select on sequence
  public.exhibitions_id_seq,
  public.contact_messages_id_seq
to service_role;

create or replace function public.replace_portfolio(
  series_items jsonb,
  work_items jsonb,
  site_settings jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if pg_catalog.jsonb_typeof(series_items) is distinct from 'array'
    or pg_catalog.jsonb_typeof(work_items) is distinct from 'array'
    or pg_catalog.jsonb_typeof(site_settings) is distinct from 'object' then
    raise exception using
      errcode = '22023',
      message = 'Invalid portfolio payload';
  end if;

  delete from public.works;
  delete from public.series;

  insert into public.series (id, slug, title, years, description, created_at, sort_order)
  select id, slug, title, years, description, created_at, sort_order
  from pg_catalog.jsonb_to_recordset(series_items) as item(
    id text,
    slug text,
    title text,
    years text,
    description text,
    created_at timestamptz,
    sort_order integer
  );

  insert into public.works (id, series_id, title, description, image, created_at, sort_order)
  select id, series_id, title, description, image, created_at, sort_order
  from pg_catalog.jsonb_to_recordset(work_items) as item(
    id text,
    series_id text,
    title text,
    description text,
    image text,
    created_at timestamptz,
    sort_order integer
  );

  insert into public.site_settings (id, settings)
  values (1, $3)
  on conflict (id) do update set settings = excluded.settings;
end;
$$;

create or replace function public.replace_exhibitions(items jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if pg_catalog.jsonb_typeof(items) is distinct from 'array' then
    raise exception using
      errcode = '22023',
      message = 'items must be a JSON array';
  end if;

  delete from public.exhibitions;

  insert into public.exhibitions (year, title, sort_order)
  select
    coalesce(pg_catalog.btrim(item->>'year'), ''),
    pg_catalog.btrim(item->>'text'),
    ordinal::integer - 1
  from pg_catalog.jsonb_array_elements(items) with ordinality as exhibition_row(item, ordinal)
  where nullif(pg_catalog.btrim(item->>'text'), '') is not null;
end;
$$;

revoke all on function public.replace_portfolio(jsonb, jsonb, jsonb)
  from public, anon, authenticated;
revoke all on function public.replace_exhibitions(jsonb)
  from public, anon, authenticated;
grant execute on function public.replace_portfolio(jsonb, jsonb, jsonb) to service_role;
grant execute on function public.replace_exhibitions(jsonb) to service_role;
